/* Run against a local server: node scripts/smoke.cjs
   Requires Playwright and Chromium (provided by the development environment). */
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const baseURL = process.env.PORTFOLIO_TEST_URL || 'http://127.0.0.1:8000';
let browser;
(async () => {
  browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--enable-unsafe-swiftshader'] });
  const errors = [];
  const page = await browser.newPage({ viewport: { width: 1440, height: 950 } });
  page.on('pageerror', error => errors.push(error.message));
  const response = await page.goto(baseURL);
  assert.equal(response.status(), 200);
  await page.waitForFunction(() => document.querySelector('#crystalAnatomy').complete && document.querySelector('#crystalAnatomy').naturalWidth > 0);
  assert.equal(await page.locator('.scene-layer').count(), 4);
  assert.equal(await page.locator('#crystalAnatomy').getAttribute('alt'), '', 'Anatomy remains decorative');
  assert.equal(await page.locator('.project').count(), 7);
  assert.match(await page.locator('.project h3').first().textContent(), /FOUNDER/);
  assert.equal(await page.locator('h1').count(), 1);
  assert.deepEqual(await page.evaluate(() => {
    const ids = [...document.querySelectorAll('[id]')].map(el => el.id);
    return ids.filter((id, index) => ids.indexOf(id) !== index);
  }), [], 'HTML IDs must be unique');
  assert.deepEqual(await page.evaluate(() => [...document.querySelectorAll('a[href^="#"]')].map(a => a.hash).filter(hash => !document.getElementById(hash.slice(1)))), [], 'Every local navigation target must exist');

  assert.equal(await page.locator('#anatomyDialog, #layerSlider, .anatomy-label').count(), 0, 'Anatomy must remain visual rather than educational');
  assert.equal(await page.locator('.strengths-card h3').count(), 3);
  await page.locator('.heart-art').scrollIntoViewIfNeeded();
  await page.waitForFunction(() => { const img = document.querySelector('.heart-art img'); return img.complete && img.naturalWidth > 0; });
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.bio-copy')).opacity === '1');
  await page.screenshot({ path: '/tmp/navya-heart-story.png' });
  assert.match(await page.locator('.intro').textContent(), /Content, creative strategy & coordination/);

  const toggle = page.locator('.menu-toggle');
  await toggle.click();
  assert.equal(await toggle.getAttribute('aria-expanded'), 'true');
  await page.locator('#siteMenu nav a').last().focus();
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(() => document.activeElement.className), 'menu-toggle', 'Menu must contain keyboard focus');
  await page.keyboard.press('Escape');
  assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
  assert.equal(await page.evaluate(() => document.querySelector('#siteMenu').inert), true);
  await toggle.click();
  await page.locator('#siteMenu a[href="#work"]').click();
  assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
  assert.equal(await page.evaluate(() => document.activeElement.id), 'work');

  // Scroll-driven state and chapter tracking, independent of animation duration.
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.locator('#journey').scrollIntoViewIfNeeded();
  await page.locator('[data-path="0"]').focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('[data-path="1"]').getAttribute('aria-pressed'), 'true');
  assert.match(await page.locator('#pathNote').textContent(), /audience, the message and the goal/);
  await page.locator('.research summary').click();
  assert.match(await page.locator('.research').textContent(), /no clinical validation established/);
  await page.locator('[data-filter="content"]').click();
  assert.equal(await page.locator('.project:not([hidden])').count(), 3);
  await page.locator('[data-filter="campaign"]').click();
  assert.equal(await page.locator('.project:not([hidden])').count(), 3);
  await page.locator('[data-filter="data"]').click();
  assert.equal(await page.locator('.project:not([hidden])').count(), 1);
  assert.match(await page.locator('#projectCount').textContent(), /1 exploration/);
  await page.locator('[data-filter="all"]').click();
  await page.locator('.project summary').first().click();
  assert.equal(await page.locator('.writing-sample').isVisible(), true);
  assert.match(await page.locator('.writing-sample').textContent(), /Fictional founder scenario/);
  assert.equal(await page.locator('.project-facts').first().isVisible(), true);
  assert.match(await page.locator('.planned-outputs').first().textContent(), /intended scope/);
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.locator('[data-share]').first().click();
  await page.waitForFunction(() => document.querySelector('.share-feedback').textContent === 'Link copied.');
  assert.match(await page.evaluate(() => navigator.clipboard.readText()), /#project-founder-linkedin-ghostwriting$/);
  await page.evaluate(() => { window.originalClipboard = navigator.clipboard; Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: () => Promise.reject(new Error('Unavailable')) } }); });
  await page.locator('[data-share]').first().click();
  assert.equal(await page.locator('.share-fallback').first().isVisible(), true);
  assert.match(await page.locator('.share-fallback').first().inputValue(), /#project-founder-linkedin-ghostwriting$/);
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: window.originalClipboard }));
  await page.goto(`${baseURL}/#project-retail-sales-dashboard`);
  await page.waitForFunction(() => document.getElementById('project-retail-sales-dashboard').open);
  assert.equal(await page.locator('.project:not([hidden])').count(), 7);
  assert.equal(await page.locator('#project-retail-sales-dashboard .project-content').isVisible(), true);
  await page.locator('#project-retail-sales-dashboard [data-enquire]').click();
  assert.match(await page.locator('#selectedBriefText').textContent(), /Power BI sales dashboard/);
  assert.equal(await page.locator('input[name="enquiryType"]:checked').inputValue(), 'collaboration');
  await page.locator('#enquiryName').fill('Example Visitor');
  await page.locator('#enquiryEmail').fill('visitor@example.com');
  await page.locator('#enquiryOrganisation').fill('Example & Co');
  await page.locator('#enquiryMessage').fill('I would like help with a dashboard & reporting brief.\nTimeline: next month.');
  await page.locator('.prepare-enquiry').click();
  assert.equal(await page.locator('#emailDraft').isVisible(), true);
  const emailDraft = new URL(await page.locator('#openEmailDraft').getAttribute('href'));
  assert.match(emailDraft.searchParams.get('subject'), /Creative collaboration: Power BI/);
  assert.match(emailDraft.searchParams.get('body'), /dashboard & reporting brief/);
  assert.match(emailDraft.searchParams.get('body'), /Example & Co/);
  await page.locator('#copyEnquiry').click();
  await page.waitForFunction(() => document.querySelector('#enquiryFeedback').textContent.startsWith('Message copied.'));
  await page.locator('#enquiryMessage').fill('Updated opportunity details.');
  assert.equal(await page.locator('#emailDraft').isVisible(), false, 'Editing invalidates a stale draft');
  await page.locator('.prepare-enquiry').click();
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: () => Promise.reject(new Error('Unavailable')) } }));
  await page.locator('#copyEnquiry').click();
  assert.equal(await page.locator('#enquiryCopyFallback').isVisible(), true);
  await page.locator('.contact-options a').first().click();
  assert.equal(await page.locator('input[name="enquiryType"]:checked').inputValue(), 'role');
  assert.equal(await page.locator('#selectedBrief').isVisible(), false);
  await page.locator('.prepare-enquiry').click();
  assert.match(await page.locator('#draftSubject').textContent(), /Role or internship enquiry — Example & Co/);
  await page.screenshot({ path: '/tmp/navya-enquiry-desktop.png' });
  await page.locator('[data-role-filter="content"]').click();
  assert.equal(await page.locator('.project:not([hidden])').count(), 3);
  await page.locator('[data-filter="all"]').click();

  assert.ok((await page.locator('.contact-options a').first().getAttribute('href')).startsWith('mailto:hello@studionavya.com'));
  await page.locator('#sound').click();
  await page.waitForFunction(() => document.querySelector('#sound').getAttribute('aria-pressed') === 'true');
  await page.locator('#sound').click();
  await page.waitForFunction(() => document.querySelector('#sound').getAttribute('aria-pressed') === 'false');
  await page.evaluate(() => scrollTo(0, document.documentElement.scrollHeight));
  await page.waitForFunction(() => document.querySelector('.chapter-rail a[aria-current]').hash === '#contact');

  for (const width of [360, 390, 600, 768, 1440, 1920]) {
    await page.setViewportSize({ width, height: 900 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `No horizontal overflow at ${width}px`);
  }
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1440, height: 950 });
  await page.goto(baseURL);
  await page.waitForFunction(() => document.querySelector('#crystalAnatomy').complete && document.querySelector('#crystalAnatomy').naturalWidth > 0);
  await page.locator('#crystalAnatomy').evaluate(el => el.decode());
  await page.screenshot({ path: '/tmp/navya-refined-desktop.png' });
  await page.evaluate(() => scrollTo({ top: document.querySelector('#work').offsetTop, behavior: 'instant' }));
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.section-heading')).opacity === '1');
  await page.screenshot({ path: '/tmp/navya-colour-work.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(baseURL);
  await page.waitForFunction(() => document.querySelector('#crystalAnatomy').complete && document.querySelector('#crystalAnatomy').naturalWidth > 0);
  await page.locator('#crystalAnatomy').evaluate(el => el.decode());
  await page.screenshot({ path: '/tmp/navya-refined-mobile.png' });
  const noJS = await browser.newContext({ javaScriptEnabled: false });
  const staticPage = await noJS.newPage();
  await staticPage.goto(baseURL);
  assert.equal(await staticPage.locator('h1').isVisible(), true);
  assert.equal(await staticPage.locator('.bio-copy').isVisible(), true);
  assert.equal(await staticPage.locator('.contact-options').isVisible(), true);
  assert.equal(await staticPage.locator('noscript').isVisible(), true);
  await noJS.close();
  assert.deepEqual(errors, [], 'No uncaught page errors');
  await browser.close(); browser = null;

  const fallbackBrowser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--disable-webgl'] });
  browser = fallbackBrowser;
  const fallbackPage = await fallbackBrowser.newPage();
  await fallbackPage.goto(baseURL);
  await fallbackPage.waitForFunction(() => document.querySelector('#crystalAnatomy').complete && document.querySelector('#crystalAnatomy').naturalWidth > 0);
  await fallbackPage.locator('.project summary').first().click();
  assert.equal(await fallbackPage.locator('.project-content').first().isVisible(), true);
  await fallbackBrowser.close(); browser = null;
  console.log('PASS: visual-only anatomy; non-tech role positioning; connected crystal artwork; keyboard menu; chapter tracking; creative process; project filters, deep links and clipboard fallback; role-fit navigation; reviewed email drafts and context handoff; research and projects; audio; six responsive widths; reduced motion; no-JS content; works with WebGL disabled.');
})().catch(async error => { console.error(error); if (browser) await browser.close(); process.exitCode = 1; });
