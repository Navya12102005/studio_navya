const assert = require('node:assert/strict');
const { chromium } = require('playwright');
let browser;
(async () => {
  browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 950 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env.PORTFOLIO_TEST_URL || 'http://127.0.0.1:8000');
  await page.locator('#crystalAnatomy').evaluate(image => image.decode());
  await page.waitForFunction(() => document.querySelector('#anatomyStage').dataset.scene === 'body');
  await page.screenshot({ path: '/tmp/navya-upper-body-desktop.png' });
  await page.locator('#mind').scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('#anatomyStage').dataset.scene === 'brain');
  await page.locator('#brainArtwork').evaluate(image => image.decode());
  await page.waitForTimeout(400);
  await page.screenshot({ path: '/tmp/navya-brain-scene.png' });
  await page.locator('#spark').scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('#anatomyStage').dataset.scene === 'neuron');
  await page.locator('#neuronArtwork').evaluate(image => image.decode());
  await page.waitForFunction(() => !document.querySelector('.neuron-signal-svg').animationsPaused());
  await page.locator('#motionToggle').click();
  await page.waitForFunction(() => document.querySelector('.neuron-signal-svg').animationsPaused());
  await page.locator('#motionToggle').click();
  await page.waitForFunction(() => !document.querySelector('.neuron-signal-svg').animationsPaused());
  await page.waitForTimeout(400);
  await page.screenshot({ path: '/tmp/navya-neuron-interior.png' });
  await page.locator('#intent').scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('#anatomyStage').dataset.scene === 'heart');
  assert.equal(await page.locator('.heart-beat').evaluate(el => getComputedStyle(el).animationPlayState), 'running');
  await page.locator('#motionToggle').click();
  assert.equal(await page.locator('#motionToggle').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('.heart-beat').evaluate(el => getComputedStyle(el).animationPlayState), 'paused');
  await page.locator('#motionToggle').click();
  await page.waitForTimeout(400);
  await page.screenshot({ path: '/tmp/navya-heart-scene.png' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await page.locator('.heart-beat').evaluate(el => getComputedStyle(el).animationName), 'none');
  await page.waitForFunction(() => document.querySelector('#motionToggle').disabled);
  assert.equal(await page.locator('#motionToggle').isDisabled(), true);
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.waitForFunction(() => !document.querySelector('#motionToggle').disabled);
  await page.locator('#about').scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('#anatomyStage').style.visibility === 'hidden');
  assert.equal(await page.locator('.heart-beat').evaluate(el => getComputedStyle(el).animationPlayState), 'paused');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(process.env.PORTFOLIO_TEST_URL || 'http://127.0.0.1:8000');
  await page.locator('#crystalAnatomy').evaluate(image => image.decode());
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: '/tmp/navya-upper-body-mobile.png', fullPage: false });
  await page.locator('#intent').scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('#anatomyStage').dataset.scene === 'heart');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  await browser.close(); browser = null;
  console.log('PASS: upper-body opening, brain/interior/heart transitions and synaptic signal controls, image loading, active heartbeat, pause/resume, reduced motion, offscreen pause and mobile fit.');
})().catch(async error => { console.error(error); if (browser) await browser.close(); process.exitCode = 1; });
