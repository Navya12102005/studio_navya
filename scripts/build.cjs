/* Dependency-free publishing build. Only active public files enter dist/. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { render } = require('../project-views.js');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'dist');
const files = ['index.html', '404.html', 'portfolio.css', 'experience.css', 'portfolio.js', 'project-views.js', 'anatomy-scene.js', 'work.js', 'config.js', 'assets/upper-body.webp', 'assets/neural-brain.webp', 'assets/neuron-interior.webp', 'assets/luminous-heart.webp', 'assets/grain.svg', 'assets/monogram.svg', 'assets/social-preview.png'];
for (const file of files) if (!fs.existsSync(path.join(root, file))) throw new Error(`Missing public file: ${file}`);
if (fs.existsSync(output)) {
  if (!fs.existsSync(path.join(output, '.portfolio-build'))) throw new Error('Refusing to replace an unrecognised dist directory.');
  fs.rmSync(output, { recursive: true });
}
fs.mkdirSync(output, { recursive: true });
fs.writeFileSync(path.join(output, '.portfolio-build'), 'Generated by scripts/build.cjs\n');
for (const file of files) {
  fs.mkdirSync(path.dirname(path.join(output, file)), { recursive: true });
  fs.copyFileSync(path.join(root, file), path.join(output, file));
}
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'work.js'), 'utf8'), context, { timeout: 1000 });
if (!Array.isArray(context.window.WORK) || !context.window.WORK.length) throw new Error('No project outlines found.');
let html = fs.readFileSync(path.join(output, 'index.html'), 'utf8');
if (!html.includes('<div id="projectList"></div>')) throw new Error('Static project insertion point is missing.');
html = html.replace('<div id="projectList"></div>', `<div id="projectList">${render(context.window.WORK)}</div>`);
html = html.replace(/<noscript>.*?<\/noscript>/s, '<noscript><p>All project outlines are readable below. For enquiries, email <a href="mailto:hello@studionavya.com">hello@studionavya.com</a>.</p></noscript>');
const suppliedURL = process.env.SITE_URL || process.env.URL || (process.env.VERCEL_PROJECT_PRODUCTION_URL ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}` : '') || (process.env.VERCEL_URL ? `https://${process.env.VERCEL_URL}` : '');
let origin = '';
if (suppliedURL) {
  const url = new URL(suppliedURL);
  if (url.protocol !== 'https:' || url.username || url.password) throw new Error('SITE_URL must be a public HTTPS website URL without credentials.');
  origin = url.origin;
  html = html.replace('content="assets/social-preview.png"', `content="${origin}/assets/social-preview.png"`);
  html = html.replace('</head>', `<link rel="canonical" href="${origin}/"><meta property="og:url" content="${origin}/"><meta name="twitter:image" content="${origin}/assets/social-preview.png"></head>`);
  fs.writeFileSync(path.join(output, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"><url><loc>${origin}/</loc></url></urlset>\n`);
}
fs.writeFileSync(path.join(output, 'index.html'), html);
fs.writeFileSync(path.join(output, 'robots.txt'), `User-agent: *\nAllow: /\n${origin ? `Sitemap: ${origin}/sitemap.xml\n` : ''}`);
const policy = require('./site-policy.cjs');
const headerLines = Object.entries(policy).map(([key, value]) => `  ${key}: ${value}`).join('\n');
fs.writeFileSync(path.join(output, '_headers'), `/*\n${headerLines}\n  Cache-Control: public, max-age=0, must-revalidate\n/assets/*\n  Cache-Control: public, max-age=3600, must-revalidate\n`);
console.log(`Built dist: ${context.window.WORK.length} pre-rendered project stories, active assets only. ${origin ? `Canonical URL: ${origin}` : 'Public URL not set; canonical and sitemap will be added when the host supplies it.'}`);
