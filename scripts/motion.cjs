/* Exercise actual publishing libraries, lifecycle and graceful degradation. */
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
let browser;
(async () => {
  browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--enable-unsafe-swiftshader'] });
  const base = process.env.PORTFOLIO_TEST_URL || 'http://127.0.0.1:8000';
  const page = await browser.newPage({ viewport: { width: 1440, height: 950 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.waitForFunction(() => document.documentElement.dataset.smoothScroll === 'enabled');
  await page.waitForFunction(() => document.querySelector('.neural-atmosphere').dataset.state === 'active');
  assert.equal(await page.locator('.neural-atmosphere canvas').count(), 1);
  await page.waitForFunction(() => getComputedStyle(document.querySelector('h1')).opacity === '1');
  await page.screenshot({ path: '/tmp/navya-motion-desktop.png' });
  await page.mouse.wheel(0, 350);
  await page.waitForFunction(() => scrollY > 100);
  await page.locator('.menu-toggle').click();
  await page.waitForFunction(() => !document.querySelector('.neural-atmosphere canvas'));
  const stopped = await page.evaluate(() => scrollY);
  await page.mouse.wheel(0, 400);
  await page.waitForTimeout(200);
  assert.equal(await page.evaluate(() => scrollY), stopped, 'Menu stops wheel scrolling');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => document.querySelector('.neural-atmosphere').dataset.state === 'active');
  // Toggle directly so this check stays at the visible opening, not at the footer.
  await page.locator('#motionToggle').dispatchEvent('click');
  await page.waitForFunction(() => document.documentElement.dataset.motion === 'static');
  assert.equal(await page.locator('.neural-atmosphere canvas').count(), 0);
  assert.equal(await page.locator('html').getAttribute('data-smooth-scroll'), 'native');
  await page.locator('#motionToggle').dispatchEvent('click');
  await page.waitForFunction(() => document.querySelector('.neural-atmosphere').dataset.state === 'active');
  await page.locator('#work').scrollIntoViewIfNeeded();
  await page.waitForFunction(() => !document.querySelector('.neural-atmosphere canvas'));
  const card = page.locator('.project').first();
  await card.hover();
  assert.match(await card.getAttribute('style'), /--light-x/);
  assert.equal(await card.evaluate(el => getComputedStyle(el, '::before').pointerEvents), 'none');
  await page.screenshot({ path: '/tmp/navya-motion-projects.png' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.waitForFunction(() => document.documentElement.dataset.smoothScroll === 'native');
  assert.equal(await page.locator('h1').evaluate(el => getComputedStyle(el).opacity), '1');
  const reduced = await browser.newPage({ reducedMotion: 'reduce' });
  const requests = [];
  reduced.on('request', request => requests.push(request.url()));
  await reduced.goto(base);
  await reduced.waitForFunction(() => document.documentElement.dataset.motion === 'static');
  assert.ok(!requests.some(url => /three.min|vanta.net/.test(url)), 'Reduced motion never requests WebGL');
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await mobile.goto(base);
  await mobile.waitForFunction(() => document.documentElement.dataset.motion === 'enhanced');
  assert.equal(await mobile.locator('html').getAttribute('data-smooth-scroll'), 'native');
  assert.equal(await mobile.locator('.neural-atmosphere canvas').count(), 0);
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await mobile.screenshot({ path: '/tmp/navya-motion-mobile.png' });
  const fallback = await browser.newPage();
  await fallback.route('**/vendor/**', route => route.abort());
  fallback.on('pageerror', error => errors.push(error.message));
  await fallback.goto(base);
  await fallback.waitForFunction(() => document.documentElement.dataset.motion === 'enhanced');
  assert.equal(await fallback.locator('h1').evaluate(el => getComputedStyle(el).opacity), '1');
  assert.equal(await fallback.locator('.project').count(), 7);
  await fallback.locator('.menu-toggle').click();
  assert.equal(await fallback.locator('.menu-toggle').getAttribute('aria-expanded'), 'true');
  assert.deepEqual(errors, []);
  console.log('PASS: GSAP entrances, Lenis wheel easing, Vanta rendering and teardown, menu freeze, pause/resume, spotlights, reduced-motion downloads, native mobile scrolling and blocked-library fallback.');
})().catch(error => { console.error(error); process.exitCode = 1; })
  .finally(async () => { if (browser) await browser.close(); });
